//   - tanstackStart, viteReact, tailwindcss, tsConfigPaths, nitro (build-only using cloudflare as a default target),
//     componentTagger (dev-only), VITE_* env injection, @ path alias, React/TanStack dedupe,
//     error logger plugins, and sandbox detection (port/host/strictPort).
// You can pass additional config via defineConfig({ vite: { ... }, etc... }) if needed.
import { defineConfig } from "@lovable.dev/vite-tanstack-config";

const onVercel = Boolean(process.env.VERCEL);

// Public site URL used for canonical links, the sitemap and the social share image.
// Set SITE_URL in the Vercel dashboard for a custom domain; otherwise Vercel's production URL is used.
const siteUrl = (
  process.env.SITE_URL ??
  (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : "")
).replace(/\/$/, "");

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  // Build for Vercel when deploying there; everything else keeps the default target.
  ...(onVercel ? { nitro: { preset: "vercel" } } : {}),
  vite: {
    define: { __SITE_URL__: JSON.stringify(siteUrl) },
  },
});
